const SCANNER_ONLY_NAV_ITEMS = [
  { href: '/scan', label: 'Scan' },
];

export function RetailerSidebar({
  accessRole,
  onClose,
}: {
  accessRole: string;
  onClose?: () => void;
}) {
  const pathname = usePathname();
  const navItems =
    accessRole === 'scanner_only' ? SCANNER_ONLY_NAV_ITEMS : ALL_NAV_ITEMS;

  return (
    <aside className="w-56 shrink-0 flex flex-col h-full bg-brand">
      <div className="h-14 flex items-center justify-between px-4 border-b border-white/10 shrink-0">
        <Logo variant="horizontal" scheme="dark" height={22} className="brightness-0 invert" />
        {onClose && (
          <button
            onClick={onClose}
            className="lg:hidden p-1 text-green-300 hover:text-white"
            aria-label="Close navigation"
          >
            <svg className="w-4 h-4" fill="none" stroke="currentColor" strokeWidth={2} viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        )}
      </div>
      <nav className="flex-1 py-3 space-y-0.5 px-2 overflow-y-auto">
        {navItems.map((item) => {
          const isActive = pathname.startsWith(item.href);
          return (
            <Link
              key={item.href}
              href={item.href}
              onClick={onClose}
              className={`flex items-center gap-2.5 px-3 py-2 rounded-lg text-sm transition-colors ${
                isActive
                  ? 'bg-white/10 text-white font-medium'
                  : 'text-green-200/75 hover:bg-white/5 hover:text-green-50'
              }`}
            >
              {ICONS[item.href]}
              <span>{item.label}</span>
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}
